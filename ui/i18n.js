let LANG = "de";

function pickLang(saved) {
  if (saved && STRINGS[saved]) return saved;
  const nav = (navigator.language || "de").slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : "en";
}

/* t("key", {name: "x"}) – falls back to English, then to the key itself. */
function t(key, args = {}) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.en[key];
  if (s === undefined) return null;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    let v = args[k];
    if (k === "stage" && v && STRINGS[LANG]["stage." + v]) v = STRINGS[LANG]["stage." + v];
    return v === undefined ? "" : v;
  });
}
/* Like t(), but returns `fallback` (or the key) for unknown keys. */
function tt(key, args, fallback) {
  const s = t(key, args);
  return s === null ? (fallback ?? key) : s;
}

/* Static markup: data-i18n (text), data-i18n-html (trusted markup),
 * data-i18n-placeholder, data-i18n-aria (aria-label). */
function applyStaticI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = tt(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = tt(el.dataset.i18nHtml)));
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = tt(el.dataset.i18nPlaceholder)));
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", tt(el.dataset.i18nAria)));
}
